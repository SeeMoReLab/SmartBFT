// reportClientID is a constant so that two nodes submitting different report
// sets for the same episode produce the same bft.RequestInfo. That is what
// makes SmartBFT's request pool treat them as one request: the second variant
// is rejected on admission, and whichever variant is ordered evicts the others
// from every node's pool when it is delivered.
const reportClientID = "reports"

const (
	deliverQueueSize = 64
	// The report chain carries one small batch per node per episode. Its
	// timeouts are fixed on purpose: this is the control plane that carries
	// timeout recommendations, so it must never be tuned by the recommendations
	// it carries.
	reportBatchMaxCount     = 32
	reportBatchMaxInterval  = 20 * time.Millisecond
	reportRequestTimeout    = 5 * time.Second
	reportViewChangeTimeout = 20 * time.Second
	reportRequestMaxBytes   = 1024 * 1024
)

type blockData struct {
	Requests [][]byte
}

type blockHeader struct {
	PrevHash string
	DataHash string
	Sequence int64
}

func encodeBlockData(data blockData) []byte {
	var out bytes.Buffer
	if err := gob.NewEncoder(&out).Encode(data); err != nil {
		panic(fmt.Sprintf("encode report block: %v", err))
	}
	return out.Bytes()
}

func decodeBlockData(raw []byte) (blockData, error) {
	var data blockData
	err := gob.NewDecoder(bytes.NewReader(raw)).Decode(&data)
	return data, err
}

func hashBytes(raw []byte) string {
	sum := sha256.Sum256(raw)
	return hex.EncodeToString(sum[:])
}

func reportRequestInfo(episode uint32) bft.RequestInfo {
	return bft.RequestInfo{
		ClientID: reportClientID,
		ID:       strconv.FormatUint(uint64(episode), 10),
	}
}

// The adaptive_timers stubs are generated by gogo protobuf while smartbftprotos
// uses the google runtime, so report batches must be (un)marshaled with gogo.
func decodeReportBatch(raw []byte) (*adaptivetimers.ReportBatch, error) {
	batch := &adaptivetimers.ReportBatch{}
	if err := gogoproto.Unmarshal(raw, batch); err != nil {
		return nil, fmt.Errorf("decode report batch: %w", err)
	}
	return batch, nil
}

func encodeReportBatch(batch *adaptivetimers.ReportBatch) ([]byte, error) {
	return gogoproto.Marshal(batch)
}

type reportNodeOptions struct {
	ID        uint64
	Hosts     []hostEntry
	Protocol  adaptivetimers.Protocol
	DataDir   string
	Logger    smart.Logger
	Transport *reportTransport
	Agent     *agentClient
}

// reportNode runs one replica of the report chain. Its state machine is
// deliberately trivial: an ordered stream of agreed ReportBatches, each handed
// to the local learning agent exactly once.
type reportNode struct {
	id        uint64
	protocol  adaptivetimers.Protocol
	numNodes  int
	quorum    int
	logger    smart.Logger
	transport *reportTransport
	agent     *agentClient
	consensus *smartbft.Consensus

	clock     *time.Ticker
	viewClock *time.Ticker

	lock             sync.Mutex
	prevHash         string
	lastDecision     bft.Decision
	haveDecision     bool
	highestDelivered uint32

	deliverQueue chan *adaptivetimers.ReportBatch
	stopChan     chan struct{}
	stopOnce     sync.Once
	doneWG       sync.WaitGroup
}

func newReportNode(opts reportNodeOptions) (*reportNode, error) {
	nodeDir := filepath.Join(opts.DataDir, fmt.Sprintf("sharing-node-%d", opts.ID))
	metricsProvider := &disabled.Provider{}
	walMetrics := wal.NewMetrics(metricsProvider, "sharing")
	bftMetrics := smart.NewMetrics(metricsProvider, "sharing")

	writeAheadLog, err := wal.Create(opts.Logger, nodeDir, &wal.Options{
		Metrics: walMetrics.With("node", fmt.Sprintf("%d", opts.ID)),
	})
	if err != nil {
		return nil, fmt.Errorf("create report chain WAL for node %d: %w", opts.ID, err)
	}

	n := &reportNode{
		id:           opts.ID,
		protocol:     opts.Protocol,
		numNodes:     len(opts.Hosts),
		quorum:       quorum(len(opts.Hosts)),
		logger:       opts.Logger,
		transport:    opts.Transport,
		agent:        opts.Agent,
		clock:        time.NewTicker(10 * time.Millisecond),
		viewClock:    time.NewTicker(100 * time.Millisecond),
		deliverQueue: make(chan *adaptivetimers.ReportBatch, deliverQueueSize),
		stopChan:     make(chan struct{}),
	}

	config := bft.DefaultConfig
	config.SelfID = opts.ID
	config.RequestBatchMaxCount = reportBatchMaxCount
	config.RequestBatchMaxInterval = reportBatchMaxInterval
	config.RequestPoolSize = 1024
	config.RequestMaxBytes = reportRequestMaxBytes
	config.RequestBatchMaxBytes = reportRequestMaxBytes * reportBatchMaxCount
	config.RequestForwardTimeout = reportRequestTimeout
	config.RequestComplainTimeout = reportRequestTimeout
	config.RequestAutoRemoveTimeout = 3 * reportRequestTimeout
	config.ViewChangeTimeout = reportViewChangeTimeout
	config.LeaderHeartbeatTimeout = 30 * time.Second
	config.LeaderRotation = false
	config.DecisionsPerLeader = 0

	n.consensus = &smartbft.Consensus{
		Config:             config,
		ViewChangerTicker:  n.viewClock.C,
		Scheduler:          n.clock.C,
		Logger:             opts.Logger,
		Metrics:            bftMetrics,
		Comm:               n,
		Signer:             n,
		MembershipNotifier: n,
		Verifier:           n,
		Application:        n,
		Assembler:          n,
		RequestInspector:   n,
		Synchronizer:       n,
		WAL:                writeAheadLog,
		Metadata: &smartbftprotos.ViewMetadata{
			LatestSequence: 0,
			ViewId:         0,
		},
	}

	if err := n.consensus.Start(); err != nil {
		n.clock.Stop()
		n.viewClock.Stop()
		return nil, fmt.Errorf("start report chain consensus for node %d: %w", opts.ID, err)
	}
	n.startDeliveryWorker()
	return n, nil
}

// startDeliveryWorker keeps the agent hand-off off the consensus thread. The
// agent applies aggregated rewards and runs model inference under a global
// lock, so calling it inline from Deliver would stall the report chain.
func (n *reportNode) startDeliveryWorker() {
	n.doneWG.Add(1)
	go func() {
		defer n.doneWG.Done()
		for {
			select {
			case <-n.stopChan:
				return
			case batch := <-n.deliverQueue:
				n.agent.deliverConsensus(batch)
			}
		}
	}()
}

func (n *reportNode) stop() {
	n.stopOnce.Do(func() { close(n.stopChan) })
	n.clock.Stop()
	n.viewClock.Stop()
	n.consensus.Stop()
	n.doneWG.Wait()
}

// submit hands a locally collected batch to the report chain. Duplicate
// episodes are expected: every node submits the same episode independently, and
// only one submission needs to survive.
func (n *reportNode) submit(raw []byte) error {
	return n.consensus.SubmitRequest(raw)
}

func (n *reportNode) handleConsensusMessage(from uint64, raw []byte) error {
	msg := &smartbftprotos.Message{}
	if err := proto.Unmarshal(raw, msg); err != nil {
		return fmt.Errorf("decode report consensus message: %w", err)
	}
	n.consensus.HandleMessage(from, msg)
	return nil
}

func (n *reportNode) handleForwardedRequest(from uint64, raw []byte) error {
	if _, err := n.VerifyRequest(raw); err != nil {
		return err
	}
	return n.consensus.HandleRequest(from, raw)
}

func (n *reportNode) leaderID() uint64 {
	return n.consensus.GetLeaderID()
}

