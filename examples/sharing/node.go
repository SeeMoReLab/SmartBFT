// --- bft.RequestInspector ---

func (n *reportNode) RequestID(raw []byte) bft.RequestInfo {
	batch, err := decodeReportBatch(raw)
	if err != nil {
		return bft.RequestInfo{}
	}
	return reportRequestInfo(batch.Episode)
}

// --- bft.Verifier ---

// VerifyRequest performs structural validation only. Report signing is off in
// these experiments, so individual reports inside a batch are not authenticated
// here; the agent applies the same policy.
func (n *reportNode) VerifyRequest(raw []byte) (bft.RequestInfo, error) {
	batch, err := decodeReportBatch(raw)
	if err != nil {
		return bft.RequestInfo{}, err
	}
	if batch.Protocol != adaptivetimers.Protocol_PROTOCOL_UNSPECIFIED && batch.Protocol != n.protocol {
		return bft.RequestInfo{}, fmt.Errorf("report batch protocol mismatch: expected=%s got=%s",
			n.protocol, batch.Protocol)
	}
	if len(batch.Reports) < n.quorum {
		return bft.RequestInfo{}, fmt.Errorf("report batch for episode %d has %d reports, need at least %d",
			batch.Episode, len(batch.Reports), n.quorum)
	}
	seen := make(map[uint32]struct{}, len(batch.Reports))
	for _, report := range batch.Reports {
		if report.Episode != batch.Episode {
			return bft.RequestInfo{}, fmt.Errorf("report from node %d carries episode %d, batch is episode %d",
				report.NodeId, report.Episode, batch.Episode)
		}
		if _, duplicate := seen[report.NodeId]; duplicate {
			return bft.RequestInfo{}, fmt.Errorf("report batch for episode %d has duplicate node %d",
				batch.Episode, report.NodeId)
		}
		seen[report.NodeId] = struct{}{}
	}
	return reportRequestInfo(batch.Episode), nil
}

func (n *reportNode) VerifyProposal(proposal bft.Proposal) ([]bft.RequestInfo, error) {
	data, err := decodeBlockData(proposal.Payload)
	if err != nil {
		return nil, err
	}
	requests := make([]bft.RequestInfo, 0, len(data.Requests))
	for _, raw := range data.Requests {
		info, err := n.VerifyRequest(raw)
		if err != nil {
			return nil, err
		}
		requests = append(requests, info)
	}
	return requests, nil
}

// RequestsFromProposal must agree with VerifyProposal: the infos it returns are
// what evicts pending duplicates from the pool on the view change delivery path.
func (n *reportNode) RequestsFromProposal(proposal bft.Proposal) []bft.RequestInfo {
	data, err := decodeBlockData(proposal.Payload)
	if err != nil {
		return nil
	}
	requests := make([]bft.RequestInfo, 0, len(data.Requests))
	for _, raw := range data.Requests {
		info := n.RequestID(raw)
		if info.ClientID == "" && info.ID == "" {
			continue
		}
		requests = append(requests, info)
	}
	return requests
}

