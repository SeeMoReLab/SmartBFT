// --- bft.Assembler ---

func (n *reportNode) AssembleProposal(metadata []byte, requests [][]byte) bft.Proposal {
	payload := encodeBlockData(blockData{Requests: requests})
	md := &smartbftprotos.ViewMetadata{}
	if err := proto.Unmarshal(metadata, md); err != nil {
		panic(fmt.Sprintf("unmarshal report proposal metadata: %v", err))
	}

	n.lock.Lock()
	prevHash := n.prevHash
	n.lock.Unlock()

	header, err := json.Marshal(blockHeader{
		PrevHash: prevHash,
		DataHash: hashBytes(payload),
		Sequence: int64(md.LatestSequence),
	})
	if err != nil {
		panic(fmt.Sprintf("marshal report block header: %v", err))
	}

	return bft.Proposal{
		Header:   header,
		Payload:  payload,
		Metadata: metadata,
	}
}

// --- bft.Application ---

func (n *reportNode) Deliver(proposal bft.Proposal, signatures []bft.Signature) bft.Reconfig {
	data, err := decodeBlockData(proposal.Payload)
	if err != nil {
		n.logger.Errorf("report node %d failed to decode proposal payload: %v", n.id, err)
		return bft.Reconfig{}
	}

	md := &smartbftprotos.ViewMetadata{}
	if err := proto.Unmarshal(proposal.Metadata, md); err != nil {
		n.logger.Errorf("report node %d failed to decode proposal metadata: %v", n.id, err)
	}

	for _, raw := range data.Requests {
		batch, err := decodeReportBatch(raw)
		if err != nil {
			n.logger.Errorf("report node %d failed to decode delivered batch: %v", n.id, err)
			continue
		}
		if !n.markDelivered(batch.Episode) {
			continue
		}
		fmt.Printf("%s delivered: node=%d view=%d seq=%d episode=%d reports=%d contributors=%v\n",
			logTag("sharing"), n.id, md.GetViewId(), md.GetLatestSequence(),
			batch.Episode, len(batch.Reports), contributorIDs(batch))
		n.enqueueDelivery(batch)
	}

	n.recordDecision(proposal, signatures)
	return bft.Reconfig{InLatestDecision: false}
}

func (n *reportNode) markDelivered(episode uint32) bool {
	n.lock.Lock()
	defer n.lock.Unlock()
	if episode <= n.highestDelivered {
		return false
	}
	n.highestDelivered = episode
	return true
}

func (n *reportNode) recordDecision(proposal bft.Proposal, signatures []bft.Signature) {
	n.lock.Lock()
	defer n.lock.Unlock()
	n.prevHash = proposal.Digest()
	n.lastDecision = bft.Decision{
		Proposal:   cloneProposal(proposal),
		Signatures: cloneSignatures(signatures),
	}
	n.haveDecision = true
}

func (n *reportNode) latestDecision() (bft.Decision, bool) {
	n.lock.Lock()
	defer n.lock.Unlock()
	if !n.haveDecision {
		return bft.Decision{}, false
	}
	return bft.Decision{
		Proposal:   cloneProposal(n.lastDecision.Proposal),
		Signatures: cloneSignatures(n.lastDecision.Signatures),
	}, true
}

func (n *reportNode) enqueueDelivery(batch *adaptivetimers.ReportBatch) {
	select {
	case n.deliverQueue <- batch:
	case <-n.stopChan:
	default:
		fmt.Printf("%s dropped delivery: node=%d episode=%d queue full\n",
			logTag("sharing"), n.id, batch.Episode)
	}
}

func contributorIDs(batch *adaptivetimers.ReportBatch) []uint32 {
	ids := make([]uint32, 0, len(batch.Reports))
	for _, report := range batch.Reports {
		ids = append(ids, report.NodeId)
	}
	return ids
}

func cloneProposal(proposal bft.Proposal) bft.Proposal {
	return bft.Proposal{
		Payload:              append([]byte(nil), proposal.Payload...),
		Header:               append([]byte(nil), proposal.Header...),
		Metadata:             append([]byte(nil), proposal.Metadata...),
		VerificationSequence: proposal.VerificationSequence,
	}
}

func cloneSignatures(signatures []bft.Signature) []bft.Signature {
	if len(signatures) == 0 {
		return nil
	}
	cloned := make([]bft.Signature, 0, len(signatures))
	for _, signature := range signatures {
		cloned = append(cloned, bft.Signature{
			ID:    signature.ID,
			Value: append([]byte(nil), signature.Value...),
			Msg:   append([]byte(nil), signature.Msg...),
		})
	}
	return cloned
}

func logTag(component string) string {
	return fmt.Sprintf("[%s %s]", component, time.Now().Format("2006-01-02T15:04:05.000Z07:00"))
}
